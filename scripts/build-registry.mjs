// Generates src/games/registry.js from every src/games/<id>/manifest.json.
//
//     npm run registry        regenerate + report
//     npm run registry:check  fail if the committed registry no longer matches games/
//
// The registry is committed on purpose: it is the reviewable diff of which games
// the shipped app will offer, and reading one file at startup is cheaper than
// globbing the module graph in the browser.
//
// This is the successor to the old hand-maintained list. A directory that exists
// but is not in the registry would otherwise disappear from the lobby with no
// error anywhere, which is the single most likely mistake when adding game #14.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { validateManifest } from '../src/core/manifest.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GAMES_DIR = join(ROOT, 'src', 'games');
const OUTPUT = join(GAMES_DIR, 'registry.js');
const HEADER = [
  '// GENERATED by scripts/build-registry.mjs — do not edit by hand.',
  '//',
  '// To add a game: create src/games/<id>/{manifest.json,logic.js,index.jsx},',
  '// then run `npm run registry` and commit the regenerated file.',
  "// `npm run registry:check` fails CI when this file and games/ disagree.",
  '',
  "export const generatedBy = 'scripts/build-registry.mjs';",
  '',
];

async function collectManifests() {
  const entries = await readdir(GAMES_DIR, { withFileTypes: true });
  const dirs = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();

  const problems = [];
  const manifests = [];

  for (const dir of dirs) {
    const manifestPath = join(GAMES_DIR, dir, 'manifest.json');
    if (!existsSync(manifestPath)) continue;

    // logic.js is what makes a game testable without a browser; index.jsx is what
    // makes it playable. Requiring both here is what stops a half-finished game
    // directory from being registered and then crashing the lobby.
    for (const required of ['logic.js', 'index.jsx']) {
      if (!existsSync(join(GAMES_DIR, dir, required))) {
        problems.push(`src/games/${dir}: registered but has no ${required}`);
      }
    }

    const source = `src/games/${dir}/manifest.json`;
    let raw;
    try {
      raw = JSON.parse(await readFile(manifestPath, 'utf8'));
    } catch (error) {
      problems.push(`${source}: not valid JSON (${error.message})`);
      continue;
    }
    try {
      const manifest = validateManifest(raw, { source });
      if (manifest.id !== dir) problems.push(`${source}: id "${manifest.id}" does not match directory "${dir}"`);
      manifests.push(manifest);
    } catch (error) {
      problems.push(error.message.replace(/\n/g, '\n  '));
    }
  }

  const ids = manifests.map((m) => m.id);
  const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
  if (duplicates.length > 0) {
    problems.push(`two game directories claim the same id: ${[...new Set(duplicates)].join(', ')}`);
  }

  if (problems.length > 0) {
    throw new Error(`registry generation failed:\n  ${problems.join('\n  ')}`);
  }
  return manifests.sort((a, b) => a.id.localeCompare(b.id));
}

function render(manifests) {
  return `${HEADER.join('\n')}\nexport const games = ${JSON.stringify(manifests, null, 2).replace(/\n/g, '\n')};\n`;
}

async function main() {
  const manifests = await collectManifests();
  const body = render(manifests);

  console.log(`Games found  ${manifests.length}`);
  for (const manifest of manifests) {
    console.log(`  ${manifest.id.padEnd(22)} ${manifest.contentTypes.join(',')} · ${manifest.difficulties.length} difficulties`);
  }

  if (process.argv.includes('--stdout')) {
    process.stdout.write(body);
    return;
  }

  let existing = null;
  try {
    existing = await readFile(OUTPUT, 'utf8');
  } catch {
    // Missing artifact falls through to the write/check branch below.
  }

  if (process.argv.includes('--check')) {
    if (existing === null) {
      console.error('\nregistry:check failed — src/games/registry.js does not exist. Run `npm run registry`.');
      process.exit(1);
    }
    if (existing !== body) {
      console.error(
        '\nregistry:check failed — src/games/registry.js no longer matches src/games/.\n' +
          '  A game was added, removed or edited without regenerating the registry.\n' +
          '  Run `npm run registry` and commit the regenerated file.\n'
      );
      process.exit(1);
    }
    console.log('\nregistry:check ok — src/games/registry.js matches src/games/.');
    return;
  }

  await writeFile(OUTPUT, body, 'utf8');
  console.log(`\nwrote src/games/registry.js (${manifests.length} games)`);
}

main().catch((error) => {
  console.error(`\n${error.message}\n`);
  process.exit(1);
});
